#!/bin/bash
set -euo pipefail

: "${KEYCLOAK_ADMIN_USERNAME:?Set KEYCLOAK_ADMIN_USERNAME in .env}"
: "${KEYCLOAK_ADMIN_PASSWORD:?Set KEYCLOAK_ADMIN_PASSWORD in .env}"
: "${KEYCLOAK_DB_NAME:?Set KEYCLOAK_DB_NAME in .env}"
: "${KEYCLOAK_DB_USER:?Set KEYCLOAK_DB_USER in .env}"
: "${KEYCLOAK_DB_PASSWORD:?Set KEYCLOAK_DB_PASSWORD in .env}"
: "${KEYCLOAK_HOSTNAME:?Set KEYCLOAK_HOSTNAME in .env}"

export KC_BOOTSTRAP_ADMIN_USERNAME="$KEYCLOAK_ADMIN_USERNAME"
export KC_BOOTSTRAP_ADMIN_PASSWORD="$KEYCLOAK_ADMIN_PASSWORD"
export KC_DB_URL="jdbc:postgresql://db:5432/$KEYCLOAK_DB_NAME"
export KC_DB_USERNAME="$KEYCLOAK_DB_USER"
export KC_DB_PASSWORD="$KEYCLOAK_DB_PASSWORD"
export KC_HOSTNAME="https://$KEYCLOAK_HOSTNAME"

exec /opt/keycloak/bin/kc.sh "$@"
